/**
 * Generates supabase/seed.sql (committed) from scripts/seed-data.ts.
 * Run: pnpm seed:gen   (db:reset runs it first). Blur placeholders are computed from public/photos with sharp.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { CATEGORIES, PIECES, REVIEWS, SELLERS, STORES, TICKER, type SeedPiece } from "./seed-data";

const root = path.resolve(import.meta.dirname, "..");
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;
const slugify = (s: string) =>
  s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function photoMeta(name: string) {
  const file = path.join(root, "public/photos", `${name}.jpg`);
  const buf = readFileSync(file);
  const meta = await sharp(buf).metadata();
  const blur = await sharp(buf).resize(16).jpeg({ quality: 40 }).toBuffer();
  return { w: meta.width ?? 1000, h: meta.height ?? 1000, blur: `data:image/jpeg;base64,${blur.toString("base64")}` };
}

const POOL: Record<SeedPiece["cat"], string[]> = {
  jackets: ["northstars-varsity", "giants-jacket", "green-jacket-flatlay", "jacket-flatlay-colour", "jackets-flatlay"],
  jerseys: ["jerseys-wall"],
  tees: ["graphic-tees", "ferrari-tee"],
  y2k: ["graphic-tees", "jackets-flatlay"],
  denim: ["denim-boots"],
  toys: ["pokemon-plush", "toy-wall"],
  games: ["retro-games"],
};

async function main() {
  const out: string[] = [];
  const w = (s = "") => out.push(s);

  w("-- GENERATED by scripts/generate-seed.ts. Do not edit by hand; edit scripts/seed-data.ts and run `pnpm seed:gen`.");
  w("-- MOCK DATA ONLY. Demo logins below exist only in the local database.");
  w("alter table public.pieces disable trigger pieces_guard;");
  w();

  // ---- reference ----
  for (const s of STORES) {
    w(`insert into public.stores (slug, name, address, hours, hours_confirmed, instagram, maps_query, photo_path, sort) values (${q(s.slug)}, ${q(s.name)}, ${q(s.address)}, ${j(s.hours)}, false, ${q(s.instagram)}, ${q(s.maps)}, ${s.photo ? q(s.photo) : "null"}, ${s.sort});`);
  }
  SELLERS.forEach((s, i) =>
    w(`insert into public.sellers (name, instagram, is_placeholder, sort) values (${q(s.name)}, ${q(s.instagram)}, ${s.placeholder}, ${i});`));
  CATEGORIES.forEach((c, i) =>
    w(`insert into public.categories (slug, name, measurement_kind, sort) values (${q(c.slug)}, ${q(c.name)}, ${q(c.kind)}, ${i});`));
  w(`update public.settings set allow_placeholder_prices = true, shipping_flat_cents = 1500, shipping_is_placeholder = true, ticker_messages = ${q(`{${TICKER.map((t) => `"${t}"`).join(",")}}`)}, google_rating = 4.5, google_review_count = 47;`);
  REVIEWS.forEach((r, i) =>
    w(`insert into public.reviews (author, quote, source, confirmed, sort) values (${q(r.author)}, ${q(r.quote)}, 'Google', false, ${i});`));
  w();

  // ---- demo logins (mock only) ----
  const users = [
    { id: "00000000-0000-4000-8000-0000000000a1", email: "owner@era-vintage.test", role: "owner", store: null, name: "Owner (demo)" },
    { id: "00000000-0000-4000-8000-0000000000b1", email: "barrie@era-vintage.test", role: "staff", store: "barrie", name: "Barrie staff (demo)" },
    { id: "00000000-0000-4000-8000-0000000000b2", email: "toronto@era-vintage.test", role: "staff", store: "toronto", name: "Toronto staff (demo)" },
  ];
  for (const u of users) {
    w(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change, email_change_token_new)
values ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)}, extensions.crypt('demo-password', extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '');`);
    w(`insert into auth.identities (id, provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(u.id)}, ${q(u.id)}, ${j({ sub: u.id, email: u.email, email_verified: true })}, 'email', now(), now(), now());`);
    w(`insert into public.profiles (id, role, store_id, display_name) values (${q(u.id)}, ${q(u.role)}, ${u.store ? `(select id from public.stores where slug = ${q(u.store)})` : "null"}, ${q(u.name)});`);
  }
  w();

  // ---- pieces + photos ----
  const slugs = new Set<string>();
  const metaCache = new Map<string, Awaited<ReturnType<typeof photoMeta>>>();
  const getMeta = async (n: string) => metaCache.get(n) ?? (metaCache.set(n, await photoMeta(n)), metaCache.get(n)!);
  const slugOf = new Map<string, string>();

  for (const p of PIECES) {
    let slug = slugify(p.title);
    while (slugs.has(slug)) slug += "-2";
    slugs.add(slug);
    slugOf.set(p.title, slug);

    const live = p.status === "live" || p.status === "held";
    const sold = p.status === "sold";
    const liveAt = live || sold || p.status === "archived" ? `now() - interval '${p.age} hours'` : "null";
    const cols = ["slug", "title", "description", "category_id", "store_id", "seller_id", "size", "era", "condition", "condition_notes", "authenticity_notes", "measurements", "price_cents", "price_is_placeholder", "status", "held_until", "live_at", "sold_at", "sold_via", "featured_rank", "created_at"];
    const vals = [
      q(slug), q(p.title), q(describe(p)),
      `(select id from public.categories where slug = ${q(p.cat)})`,
      `(select id from public.stores where slug = ${q(p.store)})`,
      `(select id from public.sellers where name = ${q(p.seller)})`,
      q(p.size), q(p.era), q(p.cond), q(p.notes ?? ""), q(p.authenticity ?? ""), j(p.m), String(p.price), "true", q(p.status),
      p.status === "held" ? "now() + interval '6 hours'" : "null",
      liveAt,
      sold ? `now() - interval '${p.sold!.hoursAgo} hours'` : "null",
      sold ? q(p.sold!.via === "online" ? "online" : "in_store") : "null",
      p.featured ? String(p.featured) : "null",
      `now() - interval '${Math.max(p.age, 1)} hours'`,
    ];
    w(`insert into public.pieces (${cols.join(", ")}) values (${vals.join(", ")});`);

    // 2 or 3 photos: the assigned one first, then siblings from the same pool
    const pool = POOL[p.cat];
    const more = pool.filter((n) => n !== p.photo).slice(0, p.cat === "jerseys" ? 0 : 2);
    const names = [p.photo, ...more];
    const kinds = ["front", "detail", "tag"];
    for (let i = 0; i < names.length; i++) {
      const name = names[i]!;
      const m = await getMeta(name);
      w(`insert into public.piece_photos (piece_id, kind, path, source, width, height, blur_data_url, position) values ((select id from public.pieces where slug = ${q(slug)}), ${q(kinds[i] ?? "detail")}, ${q(`/photos/${name}.jpg`)}, 'public', ${m.w}, ${m.h}, ${q(m.blur)}, ${i});`);
    }
    if (p.status === "held") {
      w(`insert into public.holds (piece_id, session_id, expires_at, extended) values ((select id from public.pieces where slug = ${q(slug)}), gen_random_uuid(), now() + interval '6 hours', true);`);
    }
  }
  w();

  // ---- demo orders (match the concept admin: EV-2377, 2379, 2380) ----
  const orders = [
    { title: "Graphic Tee Stack", num: 2377, status: "paid", ful: "pickup", store: "toronto", name: "[Customer] A", email: "customer-a@example.test", hoursAgo: 40 },
    { title: "Green Bomber and Bag Set", num: 2379, status: "paid", ful: "ship", store: null, name: "[Customer] B", email: "customer-b@example.test", hoursAgo: 20 },
    { title: "Light Wash Jeans and Boots", num: 2380, status: "paid", ful: "pickup", store: "barrie", name: "[Customer] C", email: "customer-c@example.test", hoursAgo: 3 },
  ] as const;
  for (const o of orders) {
    const piece = PIECES.find((p) => p.title === o.title)!;
    const slug = slugOf.get(o.title)!;
    const sub = piece.price, ship = o.ful === "ship" ? 1500 : 0, tax = Math.round((sub + ship) * 0.13);
    w(`insert into public.customers (email, name) values (${q(o.email)}, ${q(o.name)});`);
    w(`insert into public.orders (number, customer_id, session_id, status, fulfillment, store_id, ship_address, subtotal_cents, shipping_cents, tax_cents, total_cents, payment_provider, payment_ref, idempotency_key, paid_at, created_at)
values ('EV-${o.num}', (select id from public.customers where email = ${q(o.email)}), gen_random_uuid(), ${q(o.status)}, ${q(o.ful)}, ${o.store ? `(select id from public.stores where slug = ${q(o.store)})` : "null"}, ${o.ful === "ship" ? j({ name: o.name, line1: "[Address]", city: "Toronto", province: "ON", postal: "M5V 0A0", country: "CA" }) : "null"}, ${sub}, ${ship}, ${tax}, ${sub + ship + tax}, 'mock', 'mock_seed_${o.num}', 'seed-${o.num}', now() - interval '${o.hoursAgo} hours', now() - interval '${o.hoursAgo} hours');`);
    w(`insert into public.order_items (order_id, piece_id, title, price_cents, seller_id, store_id, committed) select o.id, p.id, p.title, p.price_cents, p.seller_id, p.store_id, true from public.orders o, public.pieces p where o.number = 'EV-${o.num}' and p.slug = ${q(slug)};`);
    w(`update public.pieces set sold_order_id = (select id from public.orders where number = 'EV-${o.num}') where slug = ${q(slug)};`);
  }
  w(`select setval('public.order_number_seq', 2381, false);`);
  w();

  // ---- the next drop: Friday 6 pm Toronto time (this week's, or next week's if that has passed) ----
  w(`insert into public.drops (name, starts_at, alert_on_release) values ('Friday Night Drop',
  case when ((date_trunc('week', now() at time zone 'America/Toronto') + interval '4 days 18 hours') at time zone 'America/Toronto') > now()
       then ((date_trunc('week', now() at time zone 'America/Toronto') + interval '4 days 18 hours') at time zone 'America/Toronto')
       else ((date_trunc('week', now() at time zone 'America/Toronto') + interval '11 days 18 hours') at time zone 'America/Toronto') end, true);`);
  for (const p of PIECES.filter((x) => x.drop)) {
    w(`insert into public.drop_pieces (drop_id, piece_id) select d.id, p.id from public.drops d, public.pieces p where d.name = 'Friday Night Drop' and p.slug = ${q(slugOf.get(p.title)!)};`);
  }
  w();

  // ---- a few subscribers so the admin list isn't empty ----
  w(`insert into public.subscribers (email, consent_text, source, consent_at) values ('sample-1@example.test', 'Yes, email me when new pieces drop.', 'seed', now() - interval '5 days'), ('sample-2@example.test', 'Yes, email me when new pieces drop.', 'seed', now() - interval '2 days');`);
  w();
  w("alter table public.pieces enable trigger pieces_guard;");

  writeFileSync(path.join(root, "supabase/seed.sql"), out.join("\n") + "\n");
  console.log(`wrote supabase/seed.sql (${PIECES.length} pieces)`);
}

function describe(p: SeedPiece) {
  return `${p.title}. One of one. ${p.era === "Mixed" ? "" : `${p.era} era, `}size ${p.size}. Measured flat, condition checked and photographed on the rack.`;
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
